/// Dart's `ByteData`: a view over bytes with typed accessors.
///
/// Little-endian by default, which is what `Endian.host` is on every platform
/// Flutter ships to. Dart's accessors take an optional `Endian`; the ones that
/// pass one explicitly are not translated yet and will say so rather than
/// silently reading the other way round.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ByteData {
    bytes: Vec<u8>,
}

impl ByteData {
    pub fn new(length: i64) -> Self {
        ByteData { bytes: vec![0; length.max(0) as usize] }
    }

    pub fn view(bytes: Vec<u8>) -> Self {
        ByteData { bytes }
    }

    pub fn length_in_bytes(&self) -> i64 {
        self.bytes.len() as i64
    }

    pub fn buffer(&self) -> Vec<u8> {
        self.bytes.clone()
    }

    pub fn get_uint8(&self, at: i64) -> i64 {
        self.bytes[at as usize] as i64
    }

    pub fn set_uint8(&mut self, at: i64, value: i64) {
        self.bytes[at as usize] = value as u8;
    }

    pub fn get_int8(&self, at: i64) -> i64 {
        self.bytes[at as usize] as i8 as i64
    }

    pub fn set_int8(&mut self, at: i64, value: i64) {
        self.bytes[at as usize] = value as i8 as u8;
    }

    pub fn get_uint16(&self, at: i64) -> i64 {
        u16::from_le_bytes(self.four(at, 2)[..2].try_into().unwrap()) as i64
    }

    pub fn get_int32(&self, at: i64) -> i64 {
        i32::from_le_bytes(self.four(at, 4)[..4].try_into().unwrap()) as i64
    }

    pub fn set_int32(&mut self, at: i64, value: i64) {
        let at = at as usize;
        self.bytes[at..at + 4].copy_from_slice(&(value as i32).to_le_bytes());
    }

    pub fn get_uint32(&self, at: i64) -> i64 {
        u32::from_le_bytes(self.four(at, 4)[..4].try_into().unwrap()) as i64
    }

    pub fn set_uint32(&mut self, at: i64, value: i64) {
        let at = at as usize;
        self.bytes[at..at + 4].copy_from_slice(&(value as u32).to_le_bytes());
    }

    pub fn get_float32(&self, at: i64) -> f32 {
        f32::from_le_bytes(self.four(at, 4)[..4].try_into().unwrap())
    }

    pub fn set_float32(&mut self, at: i64, value: f32) {
        let at = at as usize;
        self.bytes[at..at + 4].copy_from_slice(&value.to_le_bytes());
    }

    pub fn get_float64(&self, at: i64) -> f64 {
        f64::from_le_bytes(self.eight(at)[..8].try_into().unwrap())
    }

    pub fn set_float64(&mut self, at: i64, value: f64) {
        let at = at as usize;
        self.bytes[at..at + 8].copy_from_slice(&value.to_le_bytes());
    }

    fn four(&self, at: i64, n: usize) -> [u8; 4] {
        let at = at as usize;
        let mut out = [0u8; 4];
        out[..n].copy_from_slice(&self.bytes[at..at + n]);
        out
    }

    fn eight(&self, at: i64) -> [u8; 8] {
        let at = at as usize;
        let mut out = [0u8; 8];
        out.copy_from_slice(&self.bytes[at..at + 8]);
        out
    }
}
