/// Dart's `Duration`: a signed span counted in whole microseconds.
///
/// Not `std::time::Duration`, which is unsigned and counts nanoseconds.
/// Upstream subtracts durations and checks `isNegative`, so the sign has to
/// survive, and every Dart constructor and getter is in microseconds.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Default, Hash)]
pub struct Duration {
    pub microseconds: i64,
}

impl Duration {
    pub const ZERO: Duration = Duration { microseconds: 0 };

    pub const fn from_microseconds(microseconds: i64) -> Self {
        Duration { microseconds }
    }

    pub const fn from_milliseconds(milliseconds: i64) -> Self {
        Duration { microseconds: milliseconds * 1000 }
    }

    pub const fn from_seconds(seconds: i64) -> Self {
        Duration { microseconds: seconds * 1000000 }
    }

    /// Truncating, like Dart's: `inMilliseconds` of 1500us is 1, not 2.
    pub fn in_microseconds(&self) -> i64 {
        self.microseconds
    }

    pub fn in_milliseconds(&self) -> i64 {
        self.microseconds / 1000
    }

    pub fn in_seconds(&self) -> i64 {
        self.microseconds / 1000000
    }

    pub fn in_minutes(&self) -> i64 {
        self.microseconds / 60000000
    }

    pub fn in_hours(&self) -> i64 {
        self.microseconds / 3600000000
    }

    pub fn in_days(&self) -> i64 {
        self.microseconds / 86400000000
    }

    pub fn is_negative(&self) -> bool {
        self.microseconds < 0
    }

    pub fn abs(&self) -> Duration {
        Duration { microseconds: self.microseconds.abs() }
    }

    pub fn compare_to(&self, other: Duration) -> i64 {
        match self.microseconds.cmp(&other.microseconds) {
            std::cmp::Ordering::Less => -1,
            std::cmp::Ordering::Equal => 0,
            std::cmp::Ordering::Greater => 1,
        }
    }
}

impl std::ops::Add for Duration {
    type Output = Duration;
    fn add(self, other: Duration) -> Duration {
        Duration { microseconds: self.microseconds + other.microseconds }
    }
}

impl std::ops::Sub for Duration {
    type Output = Duration;
    fn sub(self, other: Duration) -> Duration {
        Duration { microseconds: self.microseconds - other.microseconds }
    }
}

impl std::ops::Neg for Duration {
    type Output = Duration;
    fn neg(self) -> Duration {
        Duration { microseconds: -self.microseconds }
    }
}

impl std::ops::Mul<i64> for Duration {
    type Output = Duration;
    fn mul(self, by: i64) -> Duration {
        Duration { microseconds: self.microseconds * by }
    }
}

impl fmt::Display for Duration {
    /// Dart prints `0:00:01.500000`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let us = self.microseconds.abs();
        if self.microseconds < 0 {
            write!(f, "-")?;
        }
        write!(
            f,
            "{}:{:02}:{:02}.{:06}",
            us / 3600000000,
            (us / 60000000) % 60,
            (us / 1000000) % 60,
            us % 1000000
        )
    }
}

