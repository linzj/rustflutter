// The Rust that stands in for the parts of `dart:core` and `dart:typed_data`
// that have no library to be translated from.
//
// Round 44 measured what happens when the dill's own `dart:core` is fed
// through the translator: 6608 errors became 16955, because its members are
// `external` and come out as traits with nothing in them. That measurement
// stands, and says nothing about *writing* them: a translated `Duration` is an
// empty trait, a written one is sixty lines of arithmetic.
//
