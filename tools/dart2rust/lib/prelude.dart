/// Dart's `DateTime`: an instant, counted in microseconds from the epoch.
///
/// `now()` is the one thing here that needs the outside world, and it uses the
/// system clock. Dart's is the same clock. `isUtc` is carried because upstream
/// compares on it, and the arithmetic ignores it exactly as Dart's does --
/// a `Duration` is a span, not a calendar step.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Default, Hash)]
pub struct DateTime {
    pub microseconds_since_epoch: i64,
    pub is_utc: bool,
}

impl DateTime {
    pub fn now() -> Self {
        let since = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_micros() as i64)
            .unwrap_or(0);
        DateTime { microseconds_since_epoch: since, is_utc: false }
    }

    pub fn from_microseconds_since_epoch(microseconds: i64) -> Self {
        DateTime { microseconds_since_epoch: microseconds, is_utc: false }
    }

    pub fn from_milliseconds_since_epoch(milliseconds: i64) -> Self {
        DateTime {
            microseconds_since_epoch: milliseconds * 1000,
            is_utc: false,
        }
    }

    pub fn milliseconds_since_epoch(&self) -> i64 {
        self.microseconds_since_epoch / 1000
    }

    pub fn difference(&self, other: DateTime) -> Duration {
        Duration {
            microseconds: self.microseconds_since_epoch
                - other.microseconds_since_epoch,
        }
    }

    pub fn add(&self, span: Duration) -> DateTime {
        DateTime {
            microseconds_since_epoch: self.microseconds_since_epoch
                + span.microseconds,
            is_utc: self.is_utc,
        }
    }

    pub fn subtract(&self, span: Duration) -> DateTime {
        DateTime {
            microseconds_since_epoch: self.microseconds_since_epoch
                - span.microseconds,
            is_utc: self.is_utc,
        }
    }

    pub fn is_before(&self, other: DateTime) -> bool {
        self.microseconds_since_epoch < other.microseconds_since_epoch
    }

    pub fn is_after(&self, other: DateTime) -> bool {
        self.microseconds_since_epoch > other.microseconds_since_epoch
    }
}

/// A value that belongs to one isolate, standing in a Rust `static`.
///
/// Dart's `static` is one **per isolate**, and an isolate is a thread. Rust's
/// `static` is one per *process*, so what it holds must be `Sync` -- and a
/// `Box<dyn Fn(..)>`, which is what half of Flutter's statics hold, is not and
/// never will be.
///
/// `thread_local!` says the same thing safely, and would be the right answer if
/// its value could be reached without a closure; it cannot, and
/// `Box<dyn Fn(..)>` is not `Clone`, so every read would have to be
/// restructured. This says it instead, and the `unsafe` is carrying exactly
/// one claim:
///
/// **the translated program runs on one thread.**
///
/// That is true of a Dart isolate by construction, and it is the thing to
/// check before running anything translated here: the moment this program
/// spawns a thread that touches a static, this is unsound. Nothing translated
/// so far can spawn one -- `Isolate.spawn` and `compute` are not translated --
/// and if that changes, this is where it breaks.
pub struct Isolate<T>(pub T);

unsafe impl<T> Sync for Isolate<T> {}
unsafe impl<T> Send for Isolate<T> {}

impl<T> std::ops::Deref for Isolate<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}

impl<T> std::ops::DerefMut for Isolate<T> {
    fn deref_mut(&mut self) -> &mut T {
        &mut self.0
    }
}

