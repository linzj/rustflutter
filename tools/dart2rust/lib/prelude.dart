/// `RangeError`, which carries the bounds it was given.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct RangeError {
    pub message: String,
    pub start: Option<f64>,
    pub end: Option<f64>,
}

impl RangeError {
    pub fn new(message: String) -> Self {
        RangeError { message, start: None, end: None }
    }

    pub fn range(invalid: f64, min: f64, max: f64) -> Self {
        RangeError {
            message: format!("Invalid value: not in range {}..{}: {}", min, max, invalid),
            start: Some(min),
            end: Some(max),
        }
    }
}

impl fmt::Display for RangeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "RangeError: {}", self.message)
    }
}

