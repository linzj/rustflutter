// The Rust that stands in for the parts of `dart:core` and `dart:typed_data`
// that have no library to be translated from.
//
// Round 44 measured what happens when the dill's own `dart:core` is fed
// through the translator: 6608 errors became 16955, because its members are
// `external` and come out as traits with nothing in them. That measurement
// stands, and says nothing about *writing* them: a translated `Duration` is an
// empty trait, a written one is sixty lines of arithmetic.
//
// Round 66 measured how much has to be written. The translated code calls 882
// distinct `dart:` members 30001 times, and 117 of them cover 90% of the uses.
// Most of the top of that list -- `List.[]`, `double.+`, `num.<` -- the backend
// already emits as Rust operators; what is left is the handful of *types* here.
//
// Every one of these is real. Where Dart's semantics and Rust's differ the
// difference is written down rather than smoothed over, because a stub that
// compiles and lies is worse than a name that is missing.
