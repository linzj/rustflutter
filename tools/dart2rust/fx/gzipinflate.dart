int checksum(List<int> bytes) {
  int sum = 0;
  for (final int b in bytes) {
    sum = (sum * 31 + b) % 1000003;
  }
  return sum;
}

String use() {
  final List<int> shortRaw = gzip.decode(shortGz);
  final List<int> longRaw = gzip.decode(longGz);
  final List<int> viaZlib = zlib.decode(shortZlib);
  // The isolate's result arrives later; the call is the compile's pin.
  Isolate.run<List<int>>(() => gzip.decode(longGz));
  final String text = utf8.decode(shortRaw);
  return '${text.split('\n').first}|${shortRaw.length}|${longRaw.length}:${checksum(longRaw)}|${viaZlib.length}:${checksum(viaZlib)}';
}
